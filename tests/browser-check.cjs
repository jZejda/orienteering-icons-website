const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright')

const root = path.resolve(__dirname, '..')
const output = path.join(root, 'output/browser')
const url = process.env.IOF_PREVIEW_URL || 'http://127.0.0.1:8081/'

;(async () => {
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, executablePath: process.env.IOF_CHROME || undefined })
  const errors = []
  const checks = []
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] })
    const page = await context.newPage()
    const waitForDialog = async dialog => {
      await dialog.waitFor()
      await page.waitForFunction(() => {
        const dialog = document.querySelector('[role="dialog"]')
        const panel = dialog?.querySelector('.relative')
        return dialog && panel && getComputedStyle(dialog).opacity === '1' && getComputedStyle(panel).opacity === '1'
      })
    }
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', msg => { if (msg.type() === 'warning' && msg.text().includes('[Vue warn]')) errors.push(msg.text()) })
    page.on('response', response => { if (response.url().startsWith(url) && response.status() >= 400) errors.push(`${response.status()} ${response.url()}`) })
    await page.goto(url)
    const cards = page.locator('button[data-icon-id]')
    await cards.nth(115).waitFor()
    assert.equal(await cards.count(), 116)
    assert.equal(await page.locator('button[data-category]').count(), 13)
    await page.waitForFunction(() => [...document.querySelectorAll('button[data-icon-id] svg')].every(svg => svg.getBBox().width > 0 && svg.getBBox().height > 0))
    checks.push('116 visible, painted SVGs in 12 categories')
    await page.screenshot({ path: path.join(output, 'desktop-light.png'), fullPage: true, animations: 'disabled' })

    await page.locator('[data-category="water"]').click()
    assert.equal(await cards.count(), 11)
    const search = page.locator('input[type="search"]:visible')
    await search.fill('railway')
    await page.getByText('No icons match', { exact: false }).waitFor()
    assert.equal(await cards.count(), 0)
    await search.fill('')
    await page.locator('[data-category="appearance"]').click()
    assert.equal(await cards.count(), 11)
    await page.locator('[data-category="all"]').click()
    await search.fill('minor-wather-channel')
    await page.waitForFunction(() => document.querySelectorAll('button[data-icon-id]').length === 1)
    assert.equal(await cards.first().getAttribute('data-icon-id'), 'minor-wather-channel')
    await search.fill('5.24')
    await page.waitForFunction(() => document.querySelector('button[data-icon-id]')?.dataset.iconId === 'railway')
    assert.equal(await cards.count(), 1)
    await search.fill('does-not-exist-anywhere')
    await page.getByText('No icons match', { exact: false }).waitFor()
    assert.equal(await cards.count(), 0)
    await search.fill('')
    await cards.nth(115).waitFor()
    checks.push('Category filters, reference/alias search and empty state')

    await page.locator('[data-icon-id="boulder"]').click()
    const dialog = page.getByRole('dialog', { name: 'Boulder', exact: true })
    await waitForDialog(dialog)
    await dialog.getByText('#boulder-iof-2024', { exact: true }).waitFor()
    await dialog.getByRole('button', { name: 'Copy Sprite use', exact: true }).click()
    await dialog.getByRole('status').filter({ hasText: 'Copied to clipboard' }).waitFor()
    assert.match(await page.evaluate(() => navigator.clipboard.readText()), /ioficons-sprite\.svg#boulder-iof-2024/)
    await dialog.getByRole('button', { name: 'Copy Vue component', exact: true }).click()
    assert.match(await page.evaluate(() => navigator.clipboard.readText()), /<template>[\s\S]*boulder-iof-2024/)
    const [individual] = await Promise.all([page.waitForEvent('download'), dialog.getByRole('link', { name: 'Download SVG', exact: true }).click()])
    assert.equal(individual.suggestedFilename(), 'boulder-iof-2024.svg')
    assert.equal(fs.readFileSync(await individual.path(), 'utf8'), fs.readFileSync(path.join(root, 'public/icons/boulder-iof-2024.svg'), 'utf8'))
    const [sprite] = await Promise.all([page.waitForEvent('download'), dialog.getByRole('link', { name: 'Download sprite', exact: true }).click()])
    assert.equal(sprite.suggestedFilename(), 'ioficons-sprite.svg')
    assert.equal(fs.readFileSync(await sprite.path(), 'utf8'), fs.readFileSync(path.join(root, 'public/ioficons-sprite.svg'), 'utf8'))
    await page.screenshot({ path: path.join(output, 'boulder-dialog.png'), animations: 'disabled' })
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'detached' })
    assert.equal(await page.getByRole('dialog').count(), 0)
    assert.equal(await page.evaluate(() => document.activeElement.dataset.iconId), 'boulder')
    checks.push('Corrected default, both real clipboard snippets, both SVG downloads, Escape/focus return')

    await page.getByRole('button', { name: 'Toggle theme' }).click()
    assert.equal(await page.locator('html').evaluate(el => el.classList.contains('dark')), true)
    await page.evaluate(() => scrollTo(0, 0))
    await page.screenshot({ path: path.join(output, 'desktop-dark.png'), fullPage: true, animations: 'disabled' })
    await search.fill('paved-area')
    await page.locator('[data-icon-id="paved-area"]').click()
    const darkDialog = page.getByRole('dialog', { name: 'Paved area', exact: false })
    await waitForDialog(darkDialog)
    const glyphColor = await darkDialog.locator('svg.ioficon').evaluate(el => getComputedStyle(el).color)
    assert.equal((glyphColor.match(/\d+/g) || []).slice(0, 3).every(value => Number(value) > 200), true, `Dark dialog glyph must inherit a light color: ${glyphColor}`)
    await page.screenshot({ path: path.join(output, 'paved-area-dark.png'), animations: 'disabled' })
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'detached' })
    checks.push('Dark theme and patterned icon dialog')

    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(url)
    await cards.nth(115).waitFor()
    await page.getByRole('button', { name: 'Browse 116 icons' }).click()
    const mobileSearch = page.locator('input[type="search"]:visible')
    assert.equal(await mobileSearch.evaluate(el => el === document.activeElement), true)
    await mobileSearch.fill('map-flip')
    await page.locator('[data-icon-id="map-flip"]').click()
    await waitForDialog(page.getByRole('dialog', { name: 'Map Flip' }))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.screenshot({ path: path.join(output, 'mobile-dialog.png'), animations: 'disabled' })
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'detached' })
    await mobileSearch.fill('')
    await page.locator('[data-category="flag-location"]').click()
    await page.waitForFunction(() => document.querySelectorAll('button[data-icon-id]').length === 14)
    await page.screenshot({ path: path.join(output, 'mobile-categories.png'), fullPage: true, animations: 'disabled' })
    checks.push('Mobile search focus, modal, category scrolling and no horizontal overflow')

    await page.goto(new URL('does-not-exist', url).href)
    await page.getByText('404', { exact: false }).first().waitFor()
    await page.goto(url)
    await cards.nth(115).waitFor()
    checks.push('Root route, unknown route and return to catalog')
    assert.deepEqual(errors, [])
    fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify({ url, checks, errors }, null, 2) + '\n')
    console.log(JSON.stringify({ checks, errors }, null, 2))
  } finally {
    await browser.close()
  }
})().catch(e => { console.error(e); process.exitCode = 1 })
